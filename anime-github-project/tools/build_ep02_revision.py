def build_reading() -> list[dict]:
    entries = []
    for i, (cut, ch, text, reading, pause) in enumerate(LINES, 1):
        sp, st, sid = CAST[ch]
        lid = f"ep02_v{i:03d}"
        entries.append({
            "id": lid,
            "cut": cut,
            "character": ch,
            "speaker_name": sp,
            "style_name": st,
            "style_id": sid,
            "text": text,
            "synthesis_text": reading,
            "synthesis_source": "reading_hiragana",
            "pause_after_ms": pause,
            "clip": f"outputs\\ep02_voice_reading_hiragana\\clips\\{lid}_{ch}.wav",
        })
    blob = json.dumps(entries, ensure_ascii=False, indent=2)
    for base in (KAMI, SITE):
        p = base / "assets" / "manifest_reading_hiragana_ep02.json"
        if base is KAMI or p.exists():
            p.write_text(blob, encoding="utf-8")
            print(f"reading -> {p}  ({len(entries)} lines)")
    return entries


def build_scene() -> None:
    rm = json.loads((KAMI / "assets" / "manifest_reading_hiragana_ep02.json").read_text(encoding="utf-8"))
    tl = {e["id"]: e for e in json.loads(TIMELINE.read_text(encoding="utf-8"))}
    old = json.loads((KAMI / "scene_manifest_ep02.json").read_text(encoding="utf-8"))

    # per-cut visual data (image + prompt + labels) carried from the old manifest
    cutmap: dict[str, dict] = {}
    for e in old:
        c = e["cut"]
        if c not in cutmap:
            cutmap[c] = {k: e.get(k) for k in
                         ("visualCutId", "visualCutTitle", "visualCutIndex",
                          "image", "plannedImage", "fallbackImage", "imagePrompt")}

    total = len(rm)
    scenes = []
    for i, e in enumerate(rm, 1):
        cm = cutmap[e["cut"]]
        t = tl[e["id"]]
        ch = e["character"]
        idx = cm["visualCutIndex"]
        scenes.append({
            "id": e["id"],
            "cut": e["cut"],
            "visualCutId": cm["visualCutId"],
            "visualCutTitle": cm["visualCutTitle"],
            "visualCutIndex": idx,
            "start": t["start"],
            "end": t["end"],
            "image": cm["image"],
            "plannedImage": cm["plannedImage"],
            "fallbackImage": cm["fallbackImage"],
            "imagePrompt": cm["imagePrompt"],
            "speaker": ch,
            "dialogue": e["text"],
            "reading": e["synthesis_text"],
            "log": [f"発話ログ　{i:02d}/{total}", f"担当　{ch}", "深夜帯　進行中"],
            "visualLabel": f"{idx:02d}/20　{cm['visualCutTitle']}",
            "progressLabel": f"{i:02d}/{total}　{ch}",
        })
    blob = json.dumps(scenes, ensure_ascii=False, indent=2)
    for base in (KAMI, SITE):
        p = base / "scene_manifest_ep02.json"
        p.write_text(blob, encoding="utf-8")
        print(f"scene   -> {p}  ({len(scenes)} lines, last end={scenes[-1]['end']:.1f}s)")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("stage", choices=["reading", "scene"])
    args = ap.parse_args()
    if args.stage == "reading":
        build_reading()
    else:
        build_scene()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
